-- 4b) Exceção 1: o formulário do site pode CRIAR uma marca, sempre como "lead".
--     Não pode ler, editar nem apagar nada.
drop policy if exists "formulario do site cria lead" on public.marcas;
create policy "formulario do site cria lead" on public.marcas
  for insert to anon, authenticated
  with check (
    situacao = 'lead'
    and length(nome) between 1 and 200
    and length(email) <= 200
    and length(obs) <= 3000
  );

-- 4c) Exceção 2: o site pode REGISTRAR uma visita. Não pode ler nenhuma.
drop policy if exists "site registra visita" on public.visitas;
create policy "site registra visita" on public.visitas
  for insert to anon, authenticated
  with check (length(pagina) <= 300 and length(origem) <= 120);

-- 4d) Exceção 3 (necessária para o portfólio mostrar os vídeos do banco):
--     qualquer pessoa pode LER só os vídeos marcados como visíveis.
--     Vídeo escondido no painel não aparece para ninguém além de você.
drop policy if exists "site le videos visiveis" on public.videos;
create policy "site le videos visiveis" on public.videos
  for select to anon, authenticated
  using (visivel = true);


